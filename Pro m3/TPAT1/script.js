// ตัวแปรสถานะ
let currentIndex = 0;
let userAnswers = new Array(questionsData.length).fill(null);
let rightCount = 0;
let wrongCount = 0;

// อ้างอิง DOM Elements
const questionTextEl = document.getElementById("question-text");
const optionsContainerEl = document.getElementById("options-container");
const explanationBoxEl = document.getElementById("explanation-box");
const explanationTextEl = document.getElementById("explanation-text");
const currentNumEl = document.getElementById("current-question-num");
const totalNumEl = document.getElementById("total-questions-num");
const progressBarEl = document.getElementById("progress-bar");
const scoreRightEl = document.getElementById("score-right");
const scoreWrongEl = document.getElementById("score-wrong");
const btnPrev = document.getElementById("btn-prev");
const btnNext = document.getElementById("btn-next");
const quizCardEl = document.getElementById("quiz-card");
const resultCardEl = document.getElementById("result-card");

// เริ่มต้นแอป
function initApp() {
  if (!totalNumEl) return;
  totalNumEl.textContent = questionsData.length;
  loadQuestion(currentIndex);

  if (btnPrev) btnPrev.addEventListener("click", goPrev);
  if (btnNext) btnNext.addEventListener("click", goNext);
  const btnRestart = document.getElementById("btn-restart");
  if (btnRestart) btnRestart.addEventListener("click", restartQuiz);
}

// โหลดข้อสอบ
function loadQuestion(index) {
  const q = questionsData[index];

  // อัปเดต Progress
  if (currentNumEl) currentNumEl.textContent = index + 1;
  if (progressBarEl) {
    const progressPercent = ((index + 1) / questionsData.length) * 100;
    progressBarEl.style.width = `${progressPercent}%`;
  }

  // อัปเดตคำถาม
  if (questionTextEl) questionTextEl.textContent = q.question;
  if (optionsContainerEl) {
    optionsContainerEl.innerHTML = "";
    q.options.forEach((optText, optIdx) => {
      const btn = document.createElement("button");
      btn.className = "option-btn";
      btn.textContent = optText;
      btn.addEventListener("click", () => selectOption(optIdx));

      if (userAnswers[index] !== null) {
        btn.disabled = true;
        if (optIdx === q.correctIndex) {
          btn.classList.add("selected-correct");
        } else if (optIdx === userAnswers[index]) {
          btn.classList.add("selected-wrong");
        }
      }

      optionsContainerEl.appendChild(btn);
    });
  }

  if (explanationBoxEl) {
    explanationBoxEl.classList.add("hidden");
    if (userAnswers[index] !== null) {
      showExplanation(q.explanation);
    }
  }

  if (btnPrev) btnPrev.disabled = index === 0;

  if (window.MathJax && window.MathJax.typesetPromise) {
    window.MathJax.typesetPromise();
  }
}

// ตอบคำถาม
function selectOption(selectedIdx) {
  if (userAnswers[currentIndex] !== null) return;

  const q = questionsData[currentIndex];
  userAnswers[currentIndex] = selectedIdx;

  const buttons = optionsContainerEl.querySelectorAll(".option-btn");
  buttons.forEach(btn => btn.disabled = true);

  if (selectedIdx === q.correctIndex) {
    buttons[selectedIdx].classList.add("selected-correct");
    rightCount++;
  } else {
    buttons[selectedIdx].classList.add("selected-wrong");
    buttons[q.correctIndex].classList.add("selected-correct");
    wrongCount++;
  }

  updateScoreBadge();
  showExplanation(q.explanation);
}

// แสดงคำอธิบาย
function showExplanation(text) {
  if (explanationTextEl && explanationBoxEl) {
    explanationTextEl.textContent = text;
    explanationBoxEl.classList.remove("hidden");
  }
}

// อัปเดตคะแนน
function updateScoreBadge() {
  if (scoreRightEl) scoreRightEl.textContent = `✓ ${rightCount}`;
  if (scoreWrongEl) scoreWrongEl.textContent = `✕ ${wrongCount}`;
}

// ถอยหลัง / ถัดไป
function goPrev() {
  if (currentIndex > 0) {
    currentIndex--;
    loadQuestion(currentIndex);
  }
}

function goNext() {
  if (currentIndex < questionsData.length - 1) {
    currentIndex++;
    loadQuestion(currentIndex);
  } else {
    showFinalResults();
  }
}

// แสดงหน้าสรุปผล
function showFinalResults() {
  if (quizCardEl) quizCardEl.classList.add("hidden");
  if (btnPrev) btnPrev.classList.add("hidden");
  if (btnNext) btnNext.classList.add("hidden");
  if (resultCardEl) resultCardEl.classList.remove("hidden");

  const total = questionsData.length;
  const percent = Math.round((rightCount / total) * 100);

  const finalScoreText = document.getElementById("final-score-text");
  const finalTotalText = document.getElementById("final-total-text");
  const percentageBadge = document.getElementById("percentage-badge");

  if (finalScoreText) finalScoreText.textContent = rightCount;
  if (finalTotalText) finalTotalText.textContent = total;
  if (percentageBadge) percentageBadge.textContent = `${percent}%`;
}

// เริ่มใหม่
function restartQuiz() {
  currentIndex = 0;
  rightCount = 0;
  wrongCount = 0;
  userAnswers.fill(null);
  updateScoreBadge();

  if (resultCardEl) resultCardEl.classList.add("hidden");
  if (quizCardEl) quizCardEl.classList.remove("hidden");
  if (btnPrev) btnPrev.classList.remove("hidden");
  if (btnNext) btnNext.classList.remove("hidden");

  loadQuestion(0);
}

document.addEventListener("DOMContentLoaded", initApp);